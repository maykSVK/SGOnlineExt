const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
if (pkg.version !== manifest.version) throw new Error("Package and manifest versions must match.");
const base = "https://raw.githubusercontent.com/maykSVK/SGOnlineExt/main";
const output = path.join(root, "stargame-pomocnik.user.js");
const read = file => fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n").trimEnd();
const content = manifest.content_scripts[0];
const header = `// ==UserScript==
// @name         StarGame pomocnik
// @namespace    https://github.com/maykSVK/SGOnlineExt
// @version      ${manifest.version}
// @description  Vala attacks, ideal population and sector forum drafts.
// @homepageURL  https://github.com/maykSVK/SGOnlineExt
// @match        https://stargame-online.cz/www/game.php*
// @match        https://stargame-online.cz/game.php*
// @updateURL    ${base}/stargame-pomocnik.meta.js
// @downloadURL  ${base}/stargame-pomocnik.user.js
// @run-at       document-idle
// @noframes
// @grant        GM.getValue
// @grant        GM.setValue
// @grant        GM.xmlHttpRequest
// @connect      api.github.com
// @grant        GM_addStyle
// ==/UserScript==
`;
const css = content.css.map(read).join("\n");
const bundle = `${header}\n// Generated by npm run build. Edit the source files, not this file.\n(function () {\n"use strict";\nif (document.getElementById("sgo-addon")) return;\nGM_addStyle(${JSON.stringify(css)});\n${content.js.map(read).join("\n\n")}\n})();\n`;
for (const [file, text] of [[output, bundle], [path.join(root, "stargame-pomocnik.meta.js"), header]]) {
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || read(path.basename(file)) !== text.trimEnd()) {
      throw new Error(`${path.basename(file)} is stale. Run npm run build.`);
    }
  } else {
    fs.writeFileSync(file, text, "utf8");
    console.log(`Built ${path.basename(file)}`);
  }
}
